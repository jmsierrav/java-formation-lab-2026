CREATE TABLE customers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150) NOT NULL,
    email           VARCHAR(254) NOT NULL,
    created_at      TIMESTAMP NOT NULL,

    street_type     VARCHAR(30),
    street_number   VARCHAR(30),
    number          VARCHAR(30),
    neighborhood    VARCHAR(100),
    city            VARCHAR(100),

    CONSTRAINT uq_customers_email UNIQUE (email)
);

CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(200) NOT NULL,
    price           DECIMAL(19, 4) NOT NULL,
    stock           INTEGER NOT NULL,
    version         BIGINT,

    CONSTRAINT ck_products_price_nonnegative CHECK (price >= 0),
    CONSTRAINT ck_products_stock_nonnegative CHECK (stock >= 0)
);

CREATE TABLE orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status          VARCHAR(20) NOT NULL,
    created_at      TIMESTAMP NOT NULL,
    customer_id     BIGINT NOT NULL,

    CONSTRAINT ck_orders_status
        CHECK (status IN ('PENDING', 'CONFIRMED', 'SHIPPED')),
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id) REFERENCES customers (id)
            ON DELETE RESTRICT
);

CREATE TABLE order_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity        INTEGER NOT NULL,
    unit_price      DECIMAL(19, 4) NOT NULL,
    order_id        BIGINT NOT NULL,
    product_id      BIGINT NOT NULL,

    CONSTRAINT ck_order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_order_items_unit_price_nonnegative CHECK (unit_price >= 0),
    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES orders (id)
            ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_product
        FOREIGN KEY (product_id) REFERENCES products (id)
            ON DELETE RESTRICT
);

CREATE INDEX ix_orders_customer_id ON orders (customer_id);
CREATE INDEX ix_order_items_order_id ON order_items (order_id);
CREATE INDEX ix_order_items_product_id ON order_items (product_id);
